import type { Difficulty, OptionId, Pillar, ReviewStatus } from '@/lib/config/constants';

/**
 * The seed question bank: 120 executive decision scenarios.
 *
 * Composition — 24 per pillar; 40 easy / 60 medium / 20 hard overall (8/12/4 within each pillar).
 * `tests/unit/seed-questions.test.ts` enforces every one of those counts, so the bank cannot drift.
 *
 * Writing rules applied throughout:
 *  - realistic senior HR / CXO workplace decisions, never tool or founder trivia
 *  - tests decision quality, not recall, and avoids facts that date quickly
 *  - no legal conclusions, no trick questions, no absolutes where context matters
 *  - question text under ~35 words, options under ~15 words
 *  - one clearly strongest option; distractors are plausible executive shortcuts, not jokes
 *  - the correct option is spread across a/b/c/d and is not systematically the longest
 *
 * REVIEW NOTE FOR THE EVENT OWNER: these ship as `approved` so the bank is servable out of the box.
 * Please still read them end to end in /admin/questions before the event and edit anything that does
 * not match how Outskill wants to sound in front of this audience.
 */

export type SeedQuestion = {
  code: string;
  pillar: Pillar;
  difficulty: Difficulty;
  question_text: string;
  options: { id: OptionId; text: string }[];
  correct_option_id: OptionId;
  explanation: string;
  active: boolean;
  review_status: ReviewStatus;
};

function q(
  code: string,
  pillar: Pillar,
  difficulty: Difficulty,
  question_text: string,
  optionTexts: [string, string, string, string],
  correct_option_id: OptionId,
  explanation: string,
): SeedQuestion {
  return {
    code,
    pillar,
    difficulty,
    question_text,
    options: [
      { id: 'a', text: optionTexts[0] },
      { id: 'b', text: optionTexts[1] },
      { id: 'c', text: optionTexts[2] },
      { id: 'd', text: optionTexts[3] },
    ],
    correct_option_id,
    explanation,
    active: true,
    review_status: 'approved',
  };
}

